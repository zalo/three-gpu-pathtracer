#!/usr/bin/env node

/**
 * Extracts OpenPBR LUT data and generates a JS module that creates
 * WebGPU storage buffers for the path tracer's OpenPBR integration.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.resolve(__dirname, '../third_party/openpbr-bsdf/impl/data');
const OUTPUT_PATH = path.resolve(__dirname, '../src/webgpu/OpenPBRLUTData.js');

const SIZE = 32;

function extractNumbers(filePath) {
	const content = fs.readFileSync(filePath, 'utf8');
	const cleaned = content.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
	const matches = cleaned.match(/-?\d+\.?\d*/g);
	return matches ? matches.map(Number) : [];
}

function extractVec3s(filePath) {
	const content = fs.readFileSync(filePath, 'utf8');
	const cleaned = content.replace(/\/\/.*$/gm, '');
	const matches = [...cleaned.matchAll(/vec3\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)/g)];
	const result = [];
	for (const m of matches) result.push(Number(m[1]), Number(m[2]), Number(m[3]));
	return result;
}

// Energy LUT files (uint16 values, 0-65535 → normalized to 0-1)
const energyLUTs = [
	{ id: 1, name: 'IdealDielectricAvgEnergyComplement', file: 'openpbr_ideal_dielectric_avg_energy_complement_data.h', dim: 2 },
	{ id: 2, name: 'IdealDielectricReflectionRatio', file: 'openpbr_ideal_dielectric_reflection_ratio_data.h', dim: 2 },
	{ id: 4, name: 'OpaqueDielectricAvgEnergyComplement', file: 'openpbr_opaque_dielectric_avg_energy_complement_data.h', dim: 2 },
	{ id: 5, name: 'IdealMetalEnergyComplement', file: 'openpbr_ideal_metal_energy_complement_data.h', dim: 2 },
	{ id: 6, name: 'IdealMetalAvgEnergyComplement', file: 'openpbr_ideal_metal_avg_energy_complement_data.h', dim: 2 },
];

const energy3DLUTs = [
	{ id: 0, name: 'IdealDielectricEnergyComplement', file: 'openpbr_ideal_dielectric_energy_complement_data.h' },
	{ id: 3, name: 'OpaqueDielectricEnergyComplement', file: 'openpbr_opaque_dielectric_energy_complement_data.h' },
];

// Build 2D LUT buffer: 6 layers of 32x32, each as float4 (scalar in .r)
const lut2DEntries = SIZE * SIZE * 6; // 6144 float4s
const lut2D = new Float32Array(lut2DEntries * 4);

// Layer mapping: LutId → layer index
const layerMap = { 1: 0, 2: 1, 4: 2, 5: 3, 6: 4 };

for (const lut of energyLUTs) {
	const raw = extractNumbers(path.join(DATA_DIR, lut.file));
	const layer = layerMap[lut.id];
	const count = lut.id === 6 ? SIZE : SIZE * SIZE;
	const base = layer * SIZE * SIZE;
	for (let i = 0; i < count; i++) {
		lut2D[(base + i) * 4 + 0] = (raw[i] || 0) / 65535.0;
	}
}

// LTC table (layer 5): vec3 floats
const ltcRaw = extractVec3s(path.join(DATA_DIR, 'openpbr_ltc_data.h'));
const ltcBase = 5 * SIZE * SIZE;
for (let i = 0; i < SIZE * SIZE; i++) {
	lut2D[(ltcBase + i) * 4 + 0] = ltcRaw[i * 3 + 0] || 0;
	lut2D[(ltcBase + i) * 4 + 1] = ltcRaw[i * 3 + 1] || 0;
	lut2D[(ltcBase + i) * 4 + 2] = ltcRaw[i * 3 + 2] || 0;
}

// Build 3D LUT buffers: 32^3 float4s each
function build3DLUT(file) {
	const raw = extractNumbers(path.join(DATA_DIR, file));
	const count = SIZE * SIZE * SIZE;
	const buf = new Float32Array(count * 4);
	for (let i = 0; i < count; i++) {
		buf[i * 4 + 0] = (raw[i] || 0) / 65535.0;
	}
	return buf;
}

const lut3D_0 = build3DLUT(energy3DLUTs[0].file);
const lut3D_1 = build3DLUT(energy3DLUTs[1].file);

// Generate JS output
function floatArrayToString(arr) {
	// Compact representation
	const chunks = [];
	for (let i = 0; i < arr.length; i += 64) {
		const slice = Array.from(arr.slice(i, i + 64));
		chunks.push(slice.join(','));
	}
	return chunks.join(',\n');
}

let output = `// Auto-generated by scripts/extract-openpbr-luts.js
// OpenPBR LUT data as storage buffers for WebGPU
// DO NOT EDIT

const LUT_2D_DATA = new Float32Array([
${floatArrayToString(lut2D)}
]);

const LUT_3D_0_DATA = new Float32Array([
${floatArrayToString(lut3D_0)}
]);

const LUT_3D_1_DATA = new Float32Array([
${floatArrayToString(lut3D_1)}
]);

export function createOpenPBRLUTs(device) {
\tfunction makeStorageBuffer(data) {
\t\tconst buf = device.createBuffer({
\t\t\tsize: data.byteLength,
\t\t\tusage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST,
\t\t\tmappedAtCreation: true,
\t\t});
\t\tnew Float32Array(buf.getMappedRange()).set(data);
\t\tbuf.unmap();
\t\treturn buf;
\t}

\treturn {
\t\tlut2D: makeStorageBuffer(LUT_2D_DATA),
\t\tlut3D_0: makeStorageBuffer(LUT_3D_0_DATA),
\t\tlut3D_1: makeStorageBuffer(LUT_3D_1_DATA),
\t};
}
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, output, 'utf8');

const sizeKB = (Buffer.byteLength(output, 'utf8') / 1024).toFixed(1);
console.log(`Generated OpenPBR LUT data → ${path.relative(process.cwd(), OUTPUT_PATH)} (${sizeKB} KB)`);
